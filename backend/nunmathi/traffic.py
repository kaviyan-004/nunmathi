"""Encrypted-traffic application classifier with calibrated uncertainty.

Pipeline
  1. ESP packet lengths are converted to inner-length estimates using the SA's solved geometry
     (L - 8 - iv - icv - 2). The residual padding (< block size) is kept as noise, so the
     classifier is trained on exactly the representation it sees at inference time.
  2. Traffic is cut into 5-second windows; each window becomes a 34-dimensional feature vector
     (size, timing, direction and burst statistics).
  3. A gradient-boosted tree ensemble is trained on synthetic windows generated by
     forge.traffic_models through randomly chosen ESP geometries (no capture data is used).
  4. Split-conformal prediction (alpha = 0.1) turns probabilities into prediction sets with a
     90 % coverage guarantee; a k-NN distance test flags out-of-distribution windows.
  5. Metadata Exposure Index (MEI) = (log2 K - H(p)) / log2 K per window: 0 means the metadata
     reveals nothing about the application, 1 means it is fully identifiable.
"""
from __future__ import annotations

import hashlib
import math
import os
import pickle
import random
from dataclasses import dataclass

import numpy as np

from .forge import traffic_models as TM
from .forge.wire import esp_geometry, pad_to

WINDOW = 5.0
MIN_PKTS = 4
ALPHA = 0.1
CLASSES = TM.CLASSES
MODEL_VERSION = "nm-traffic-2"

FEATURE_NAMES = []
for _d in ("up", "down"):
    FEATURE_NAMES += [f"{_d}_{x}" for x in ("log_pkts", "log_bytes", "len_mean", "len_std", "len_p10", "len_p50",
                                             "len_p90", "frac_large", "frac_small", "log_iat_mean", "iat_cv",
                                             "periodicity")]
FEATURE_NAMES += ["pkt_ratio_up", "byte_ratio_up", "log_iat_p50_all", "iat_cv_all", "max_burst_100ms",
                  "active_frac", "len_distinct_frac", "log_rate_pps", "dir_switch_rate", "bytes_skew"]

# geometries used to augment the synthetic training data (encr, integ)
TRAIN_GEOMETRIES = [(20, 0), (12, 2), (12, 12), (12, 14), (3, 2), (28, 0), (11, 2), (11, 12), (13, 12)]


def overhead(geo_best: dict | None) -> int:
    if not geo_best or geo_best.get("iv") is None:
        return 8 + 8 + 16 + 2
    return 8 + int(geo_best["iv"]) + int(geo_best["icv"]) + 2


# ------------------------------------------------------------------ features
def _dir_feats(ts: np.ndarray, ln: np.ndarray) -> list[float]:
    n = len(ln)
    if n == 0:
        return [0.0] * 12
    iat = np.diff(ts) if n > 1 else np.array([WINDOW])
    med = float(np.median(iat))
    periodic = float(np.mean(np.abs(iat - med) < 0.004)) if n > 2 else 0.0
    return [math.log1p(n), math.log1p(float(ln.sum())), float(ln.mean()), float(ln.std()),
            float(np.percentile(ln, 10)), float(np.percentile(ln, 50)), float(np.percentile(ln, 90)),
            float(np.mean(ln > 1200)), float(np.mean(ln < 160)),
            math.log10(float(iat.mean()) + 1e-5), float(iat.std() / (iat.mean() + 1e-9)), periodic]


def window_features(ts: np.ndarray, up: np.ndarray, ln: np.ndarray) -> list[float]:
    """ts relative seconds, up bool array, ln inner-length estimates."""
    f = _dir_feats(ts[up], ln[up]) + _dir_feats(ts[~up], ln[~up])
    n = len(ts)
    nu = int(up.sum())
    bu = float(ln[up].sum())
    bt = float(ln.sum()) + 1e-9
    iat = np.diff(ts) if n > 1 else np.array([WINDOW])
    bins = np.floor((ts - ts.min()) / 0.1).astype(int)
    burst = int(np.bincount(bins).max()) if n else 0
    sec = np.unique(np.floor(ts - ts.min()).astype(int))
    switches = float(np.sum(up[1:] != up[:-1])) / max(1, n - 1)
    f += [nu / max(1, n), bu / bt, math.log10(float(np.median(iat)) + 1e-5), float(iat.std() / (iat.mean() + 1e-9)),
          math.log1p(burst), len(sec) / WINDOW, len(np.unique(ln)) / max(1, n), math.log1p(n / WINDOW), switches,
          float(abs(bu - (bt - bu)) / bt)]
    return f


def windows_from_series(ts: np.ndarray, up: np.ndarray, ln: np.ndarray, t0: float | None = None):
    """Yield (start, end, features, n) for each non-idle WINDOW-second slice."""
    if len(ts) == 0:
        return
    order = np.argsort(ts, kind="stable")
    ts, up, ln = ts[order], up[order], ln[order]
    t0 = ts[0] if t0 is None else t0
    idx = np.floor((ts - t0) / WINDOW).astype(int)
    bounds = np.flatnonzero(np.diff(idx)) + 1
    for a, b in zip(np.r_[0, bounds], np.r_[bounds, len(ts)]):
        if b - a < MIN_PKTS:
            continue
        w0 = t0 + idx[a] * WINDOW
        yield w0, w0 + WINDOW, window_features(ts[a:b] - w0, up[a:b], ln[a:b]), int(b - a)


# ------------------------------------------------------------------ synthetic training data
def synth_windows(n_per_class: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
    rng = random.Random(seed)
    X, y = [], []
    for ci, cls in enumerate(CLASSES):
        got = 0
        while got < n_per_class:
            encr, integ = rng.choice(TRAIN_GEOMETRIES)
            iv, b, icv = esp_geometry(encr, integ)
            dur = rng.uniform(15, 40)
            pk = TM.generate(cls, rng, dur)
            if not pk:
                continue
            ts = np.array([p[0] for p in pk]) + rng.uniform(0, WINDOW)
            up = np.array([p[1] == "up" for p in pk])
            esp = np.array([8 + iv + pad_to(p[2] + 2, b) + icv for p in pk])
            ln = esp - (8 + iv + icv + 2)
            jitter = np.array([rng.gauss(0, 0.0008) for _ in pk])
            for _, _, f, _ in windows_from_series(ts + jitter, up, ln.astype(float), t0=0.0):
                X.append(f)
                y.append(ci)
                got += 1
    return np.array(X, dtype=float), np.array(y)


# ------------------------------------------------------------------ model
@dataclass
class TrafficModel:
    clf: object
    qhat: float
    mu: np.ndarray
    sd: np.ndarray
    nn_train: np.ndarray
    ood_threshold: float
    card: dict

    def _z(self, X: np.ndarray) -> np.ndarray:
        return (X - self.mu) / self.sd

    def _nn_dist(self, X: np.ndarray, k: int = 5) -> np.ndarray:
        Z = self._z(X)
        out = np.empty(len(Z))
        for i in range(0, len(Z), 256):
            d = ((Z[i:i + 256, None, :] - self.nn_train[None, :, :]) ** 2).sum(-1)
            d.sort(axis=1)
            out[i:i + 256] = np.sqrt(d[:, :k]).mean(1)
        return out

    def predict(self, X: np.ndarray) -> list[dict]:
        if len(X) == 0:
            return []
        P = self.clf.predict_proba(X)
        dist = self._nn_dist(X)
        K = len(CLASSES)
        res = []
        for p, dd in zip(P, dist):
            pset = [CLASSES[k] for k in np.argsort(-p) if 1 - p[k] <= self.qhat] or [CLASSES[int(np.argmax(p))]]
            H = -sum(q * math.log2(q) for q in p if q > 0)
            res.append({"label": CLASSES[int(np.argmax(p))], "probs": {c: round(float(q), 4) for c, q in zip(CLASSES, p)},
                        "set": pset, "entropy": round(H, 4), "mei": round((math.log2(K) - H) / math.log2(K), 4),
                        "ood": bool(dd > self.ood_threshold), "ood_score": round(float(dd / self.ood_threshold), 3)})
        return res


def _make_clf():
    from sklearn.ensemble import HistGradientBoostingClassifier
    return HistGradientBoostingClassifier(max_iter=250, learning_rate=0.08, max_leaf_nodes=31,
                                          l2_regularization=1.0, random_state=0)


def train(n_per_class: int = 700, seed: int = 20260) -> TrafficModel:
    X, y = synth_windows(n_per_class, seed)
    Xc, yc = synth_windows(n_per_class // 3, seed + 1)       # calibration
    Xt, yt = synth_windows(n_per_class // 3, seed + 2)       # held-out test
    clf = _make_clf().fit(X, y)
    Pc = clf.predict_proba(Xc)
    scores = 1 - Pc[np.arange(len(yc)), yc]
    n = len(scores)
    qhat = float(np.quantile(scores, min(1.0, math.ceil((n + 1) * (1 - ALPHA)) / n), method="higher"))
    mu, sd = X.mean(0), X.std(0) + 1e-6
    rng = np.random.default_rng(seed)
    ref = ((X - mu) / sd)[rng.choice(len(X), size=min(1500, len(X)), replace=False)]
    m = TrafficModel(clf, qhat, mu, sd, ref, 1.0, {})
    m.ood_threshold = float(np.quantile(m._nn_dist(Xc), 0.99))
    # model card on the held-out synthetic test set
    pt = m.predict(Xt)
    pred = np.array([CLASSES.index(r["label"]) for r in pt])
    cover = np.mean([CLASSES[t] in r["set"] for r, t in zip(pt, yt)])
    cm = np.zeros((len(CLASSES), len(CLASSES)), int)
    for a, b in zip(yt, pred):
        cm[a, b] += 1
    per = {}
    for i, c in enumerate(CLASSES):
        tp = cm[i, i]
        prec = tp / max(1, cm[:, i].sum())
        rec = tp / max(1, cm[i].sum())
        per[c] = {"precision": round(float(prec), 3), "recall": round(float(rec), 3),
                  "f1": round(float(2 * prec * rec / max(1e-9, prec + rec)), 3)}
    m.card = {
        "model": "HistGradientBoostingClassifier (250 iters, 31 leaves)", "version": MODEL_VERSION,
        "classes": CLASSES, "window_seconds": WINDOW, "features": FEATURE_NAMES,
        "training": {"source": "synthetic (forge.traffic_models) through randomized ESP geometries",
                     "geometries": [f"encr {e} / integ {i}" for e, i in TRAIN_GEOMETRIES],
                     "train_windows": int(len(y)), "calibration_windows": int(len(yc)), "test_windows": int(len(yt))},
        "test_accuracy": round(float((pred == yt).mean()), 4),
        "macro_f1": round(float(np.mean([v["f1"] for v in per.values()])), 4),
        "per_class": per, "confusion_matrix": cm.tolist(),
        "conformal": {"alpha": ALPHA, "qhat": round(qhat, 4), "empirical_coverage": round(float(cover), 4),
                      "mean_set_size": round(float(np.mean([len(r["set"]) for r in pt])), 3)},
        "ood": {"method": "mean 5-NN distance in standardized feature space", "threshold_quantile": 0.99,
                "threshold": round(m.ood_threshold, 3)},
        "limitations": ["Trained only on synthetic traffic; accuracy on real captures will be lower and should be "
                        "re-measured with labelled local data.",
                        "Windows with fewer than 4 packets are treated as idle and not classified.",
                        "Class set is closed (voip, video, web, chat, email); anything else should surface as OOD "
                        "or as a large prediction set."],
    }
    return m


_MODEL: TrafficModel | None = None


BUNDLED = os.path.join(os.path.dirname(__file__), "models", "traffic.pkl")


def _cache_path() -> str:
    root = os.environ.get("NUNMATHI_DATA", os.path.join(os.path.dirname(__file__), "..", "data"))
    try:
        src = open(TM.__file__, "rb").read() + open(__file__, "rb").read()
        h = hashlib.sha256(src).hexdigest()[:12]
    except OSError:
        # frozen build (PyInstaller): sources are not on disk, key the cache by engine version instead
        from .analyzer import ENGINE_VERSION
        h = f"v{ENGINE_VERSION}"
    return os.path.join(root, "models", f"traffic-{h}.pkl")


def get_model() -> TrafficModel:
    global _MODEL
    if _MODEL is None:
        path = _cache_path()
        if not os.path.exists(path) and os.path.exists(BUNDLED):
            path = BUNDLED       # pre-trained model shipped with an installed package
        if os.path.exists(path):
            with open(path, "rb") as fh:
                _MODEL = pickle.load(fh)
        else:
            _MODEL = train()
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as fh:
                pickle.dump(_MODEL, fh)
    return _MODEL


# ------------------------------------------------------------------ inference on a tunnel
def classify_tunnel(esp_pkts: list[tuple[float, bool, int]], ovh_by_spi: dict[str, int], default_ovh: int,
                    t0: float) -> dict:
    """esp_pkts: (ts, is_up, esp_len, spi). Returns windows, segments and summary."""
    if not esp_pkts:
        return {"windows": [], "segments": [], "summary": {}}
    ts = np.array([p[0] for p in esp_pkts])
    up = np.array([p[1] for p in esp_pkts])
    ln = np.array([p[2] - ovh_by_spi.get(p[3], default_ovh) for p in esp_pkts], dtype=float)
    wins = list(windows_from_series(ts, up, ln, t0=t0))
    model = get_model()
    preds = model.predict(np.array([w[2] for w in wins])) if wins else []
    out = []
    for (a, b, f, n), p in zip(wins, preds):
        out.append({"start": a, "end": b, "packets": n, **p, "x": [round(float(v), 5) for v in f]})
    # merge consecutive windows with identical label into segments
    segs = []
    for w in out:
        if segs and segs[-1]["label"] == w["label"] and w["start"] - segs[-1]["end"] <= WINDOW + 1e-6:
            s = segs[-1]
            s["end"] = w["end"]
            s["windows"] += 1
            s["packets"] += w["packets"]
            s["_p"].append(w["probs"][w["label"]])
            s["_mei"].append(w["mei"])
            s["ood"] = s["ood"] or w["ood"]
        else:
            segs.append({"start": w["start"], "end": w["end"], "label": w["label"], "windows": 1,
                         "packets": w["packets"], "_p": [w["probs"][w["label"]]], "_mei": [w["mei"]], "ood": w["ood"]})
    for s in segs:
        s["confidence"] = round(float(np.mean(s.pop("_p"))), 3)
        s["mei"] = round(float(np.mean(s.pop("_mei"))), 3)
    counts = {c: 0 for c in CLASSES}
    for w in out:
        counts[w["label"]] += 1
    mei = [w["mei"] for w in out]
    summary = {"windows": len(out), "class_windows": counts,
               "mei_mean": round(float(np.mean(mei)), 3) if mei else None,
               "mei_p90": round(float(np.percentile(mei, 90)), 3) if mei else None,
               "singleton_sets": round(float(np.mean([len(w["set"]) == 1 for w in out])), 3) if out else None,
               "ood_windows": int(sum(w["ood"] for w in out))}
    return {"windows": out, "segments": segs, "summary": summary}
