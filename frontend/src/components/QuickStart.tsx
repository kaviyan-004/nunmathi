import { useEffect, useState } from "react";
import { api, type Analysis } from "../api";
import * as I from "../icons";

export default function QuickStart({
  current,
  onFile,
  onDemo,
}: {
  current: Analysis | null;
  onFile: (f: File | undefined) => void;
  onDemo: (s: string) => void;
}) {
  const [scen, setScen] = useState<{ id: string; title: string; description: string }[]>([]);
  const [over, setOver] = useState(false);
  const [file, setFile] = useState<File | undefined>();
  useEffect(() => {
    api.scenarios().then(setScen).catch(() => setScen([]));
  }, []);
  const running = current && (current.status === "running" || current.status === "queued");

  return (
    <div className="qs">
      <h1>Welcome to Nunmathi</h1>
      <p className="lead">
        Nunmathi is a passive analyzer for IPsec VPNs. It reads a packet capture, rebuilds every IKE and ESP
        session, and grades the tunnel's configuration. It never decrypts traffic or sends packets. Findings are
        raised as alerts with evidence and remediation. A machine-learning model estimates what kind of application
        traffic is leaking through the encryption. A what-if simulator suggests the cheapest fixes.
      </p>
      <div className="cards">
        <div className="card">
          <h3>
            <I.IcBolt /> Automated Analysis
          </h3>
          <div
            className={`drop ${over ? "over" : ""}`}
            onDragOver={(e) => {
              e.preventDefault();
              setOver(true);
            }}
            onDragLeave={() => setOver(false)}
            onDrop={(e) => {
              e.preventDefault();
              setOver(false);
              setFile(e.dataTransfer.files[0]);
            }}
          >
            Drop a <b>.pcap</b> / <b>.pcapng</b> capture here
            <div style={{ marginTop: 8 }}>
              <label className="btn">
                Select…
                <input type="file" accept=".pcap,.pcapng,.cap" hidden onChange={(e) => setFile(e.target.files?.[0])} />
              </label>
            </div>
          </div>
          <table className="kv" style={{ marginTop: 10 }}>
            <tbody>
              <tr>
                <th style={{ width: 120 }}>Capture:</th>
                <td>{file ? `${file.name} (${(file.size / 1048576).toFixed(1)} MB)` : <span className="muted">none selected</span>}</td>
              </tr>
            </tbody>
          </table>
          <button className="btn primary" disabled={!file || !!running} onClick={() => onFile(file)}>
            ⚡ Analyze
          </button>
          <div style={{ marginTop: 12 }}>
            Progress: {current ? <b>{current.name}</b> : "not started"}{" "}
            {current && <span className="muted">— {current.status === "running" ? current.stage : current.status}</span>}
            <div className="progress" style={{ marginTop: 4 }}>
              <div style={{ width: `${current ? current.progress : 0}%` }} />
            </div>
            {current?.status === "failed" && <div className="pill bad" style={{ marginTop: 6 }}>{current.error}</div>}
          </div>
        </div>
        <div className="card">
          <h3>
            <I.IcPlay /> Demo scenarios
          </h3>
          <div className="muted" style={{ marginBottom: 6 }}>
            Synthetic captures generated by the built-in traffic forge, with known ground truth.
          </div>
          {scen.map((s) => (
            <div className="scen" key={s.id}>
              <div>
                <div className="t">{s.title}</div>
                <div className="d">{s.description}</div>
              </div>
              <button className="btn" disabled={!!running} onClick={() => onDemo(s.id)}>
                Load
              </button>
            </div>
          ))}
        </div>
        <div className="card">
          <h3>
            <I.IcHelp /> What Nunmathi checks
          </h3>
          <ul style={{ margin: 0, paddingLeft: 18, lineHeight: 1.6 }}>
            <li>IKE version, mode, proposals and INVALID_KE renegotiation</li>
            <li>ESP cipher family inferred from packet-length geometry</li>
            <li>PFS inferred from the size of encrypted CREATE_CHILD_SA messages</li>
            <li>SA lifetimes from the observed rekey cadence</li>
            <li>Application-class leakage (ML, conformal prediction, OOD detection)</li>
            <li>DPD, NAT-T, fragmentation, Vendor-ID fingerprinting, half-open floods</li>
          </ul>
          <p className="muted" style={{ marginBottom: 0 }}>
            Command line: <span className="mono">python -m nunmathi analyze capture.pcap --fail-on High</span>
          </p>
        </div>
      </div>
    </div>
  );
}
